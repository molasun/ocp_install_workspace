def t(key, **kwargs):
    """Query translated string, supports format parameters"""
    lang = st.session_state.get('language', 'zh')
    text = TRANSLATIONS.get(lang, {}).get(key, key)
    if kwargs:
        text = text.format(**kwargs)
    return text


def init_language():
    """Initialize default language"""
    if 'language' not in st.session_state:
        st.session_state['language'] = 'zh'


def render_lang_selector():
    """Render language selector in top-right corner"""
    init_language()
    col_spacer, col_lang = st.columns([10, 1])
    with col_lang:
        current = st.session_state.get('language', 'zh')
        options = ['中文', 'English']
        index = 0 if current == 'zh' else 1
        selected = st.selectbox(
            "Language", options, index=index,
            key="lang_selector", label_visibility="collapsed"
        )
        new_lang = 'zh' if selected == '中文' else 'en'
        if new_lang != current:
            st.session_state['language'] = new_lang
            st.rerun()
